// client/src/components/project/erd/erdExportUtils.js
//
// Standalone SVG and PNG exporter for ArchMind AI ERD diagrams.
// Generates publication-grade vector SVG directly from layouted nodes and edges,
// and renders to high-resolution PNG using HTML5 Canvas.

/**
 * Escapes XML/SVG special characters
 */
function escapeXml(unsafe) {
  if (!unsafe) return "";
  return String(unsafe)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/**
 * Generates a complete standalone SVG document string from layouted ERD nodes and edges.
 *
 * @param {Array} nodes - React Flow layouted nodes
 * @param {Array} edges - React Flow edges
 * @param {string} title - Diagram title
 * @returns {string} Standalone SVG XML string
 */
export function generateErdSvg(nodes = [], edges = [], title = "ArchMind AI Database ERD") {
  if (!nodes || nodes.length === 0) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="200"><text x="20" y="40" fill="#fff">No entities</text></svg>`;
  }

  // Calculate bounding box across all nodes
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  const nodeWidth = 310;

  nodes.forEach((node) => {
    const x = node.position?.x || 0;
    const y = node.position?.y || 0;
    const h = node.nodeHeight || 160;

    if (x < minX) minX = x;
    if (y < minY) minY = y;
    if (x + nodeWidth > maxX) maxX = x + nodeWidth;
    if (y + h > maxY) maxY = y + h;
  });

  const padding = 80;
  const topHeaderHeight = 60;
  const totalWidth = Math.max(800, maxX - minX + padding * 2);
  const totalHeight = Math.max(600, maxY - minY + padding * 2 + topHeaderHeight);

  // Offset transformation so content starts nicely padded
  const offsetX = -minX + padding;
  const offsetY = -minY + padding + topHeaderHeight;

  // Build node position lookup for edge routing
  const nodeMap = new Map();
  nodes.forEach((n) => {
    nodeMap.set(n.id, {
      x: (n.position?.x || 0) + offsetX,
      y: (n.position?.y || 0) + offsetY,
      w: nodeWidth,
      h: n.nodeHeight || 160,
      data: n.data,
    });
  });

  let svgContent = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${totalWidth} ${totalHeight}" width="${totalWidth}" height="${totalHeight}">
  <defs>
    <!-- Background grid dot pattern -->
    <pattern id="erd-dots" x="0" y="0" width="24" height="24" patternUnits="userSpaceOnUse">
      <circle cx="2" cy="2" r="1.2" fill="#064e3b" opacity="0.4" />
    </pattern>
    <!-- Arrowhead markers -->
    <marker id="arrow-emerald" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M 0 1 L 10 5 L 0 9 z" fill="#10b981" />
    </marker>
    <marker id="arrow-cyan" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M 0 1 L 10 5 L 0 9 z" fill="#06b6d4" />
    </marker>
    <marker id="arrow-purple" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M 0 1 L 10 5 L 0 9 z" fill="#a855f7" />
    </marker>
  </defs>

  <!-- Canvas Background -->
  <rect width="100%" height="100%" fill="#04070d" />
  <rect width="100%" height="100%" fill="url(#erd-dots)" />

  <!-- Diagram Title Header -->
  <g transform="translate(${padding}, 40)">
    <circle cx="6" cy="6" r="5" fill="#10b981" />
    <text x="20" y="10" font-family="ui-sans-serif, system-ui, sans-serif" font-size="16" font-weight="bold" fill="#f8fafc">
      ${escapeXml(title)}
    </text>
    <text x="20" y="26" font-family="ui-monospace, monospace" font-size="11" fill="#94a3b8">
      Generated by ArchMind AI • ${nodes.length} Entities • ${edges.length} Relationships
    </text>
  </g>
`;

  // Draw Edges
  svgContent += `\n  <!-- Relationships (Edges) -->\n  <g class="relationships">\n`;
  edges.forEach((edge) => {
    const src = nodeMap.get(edge.source);
    const tgt = nodeMap.get(edge.target);
    if (!src || !tgt) return;

    // Connect from right of source to left of target (or closest sides)
    const x1 = src.x + src.w;
    const y1 = src.y + src.h / 2;
    const x2 = tgt.x;
    const y2 = tgt.y + tgt.h / 2;

    const dx = Math.abs(x2 - x1) * 0.5;
    const pathD = `M ${x1} ${y1} C ${x1 + dx} ${y1}, ${x2 - dx} ${y2}, ${x2} ${y2}`;

    let strokeColor = "#10b981";
    let markerId = "arrow-emerald";
    let strokeDash = "";

    if (edge.data?.type === "embedded") {
      strokeColor = "#a855f7";
      markerId = "arrow-purple";
      strokeDash = `stroke-dasharray="4,4"`;
    } else if (edge.data?.isPhysical === false) {
      strokeColor = "#06b6d4";
      markerId = "arrow-cyan";
      strokeDash = `stroke-dasharray="6,4"`;
    }

    svgContent += `    <path d="${pathD}" fill="none" stroke="${strokeColor}" stroke-width="2" ${strokeDash} marker-end="url(#${markerId})" />\n`;

    // Edge Label
    if (edge.label) {
      const midX = (x1 + x2) / 2;
      const midY = (y1 + y2) / 2;
      const labelText = escapeXml(edge.label);
      svgContent += `    <g transform="translate(${midX - 25}, ${midY - 9})">
      <rect x="0" y="0" width="50" height="18" rx="4" fill="#04070d" stroke="${strokeColor}" stroke-width="1" />
      <text x="25" y="12" font-family="ui-monospace, monospace" font-size="9" font-weight="bold" fill="${strokeColor}" text-anchor="middle">
        ${labelText}
      </text>
    </g>\n`;
    }
  });
  svgContent += `  </g>\n`;

  // Draw Nodes
  svgContent += `\n  <!-- Entity Cards -->\n  <g class="entities">\n`;
  nodes.forEach((node) => {
    const pos = nodeMap.get(node.id);
    if (!pos) return;

    const { x, y, w, h } = pos;
    const isEmbedded = Boolean(node.data?.isEmbedded);
    const borderColor = isEmbedded ? "#a855f7" : "#10b981";
    const headerBg = isEmbedded ? "#2e1065" : "#064e3b";
    const entityName = escapeXml(node.data?.name || node.id);
    const collectionName = escapeXml(node.data?.collectionName || node.data?.tableName || "");
    const fields = Array.isArray(node.data?.fields) ? node.data.fields : [];
    const previewFields = fields.slice(0, 8);

    svgContent += `    <g transform="translate(${x}, ${y})">
      <!-- Card Container -->
      <rect x="0" y="0" width="${w}" height="${h}" rx="10" fill="#08131e" stroke="${borderColor}" stroke-width="1.5" />
      <!-- Header Background -->
      <path d="M 0 10 Q 0 0 10 0 L ${w - 10} 0 Q ${w} 0 ${w} 10 L ${w} 42 L 0 42 Z" fill="${headerBg}" opacity="0.6" />
      <line x1="0" y1="42" x2="${w}" y2="42" stroke="#334155" stroke-width="1" />

      <!-- Header Icon & Name -->
      <text x="14" y="24" font-family="ui-sans-serif, system-ui, sans-serif" font-size="12" font-weight="bold" fill="#f8fafc">
        ${isEmbedded ? "◈ " : "⬡ "}${entityName}
      </text>
      <text x="14" y="37" font-family="ui-monospace, monospace" font-size="9" fill="#34d399">
        ${collectionName}
      </text>
      <!-- Fields Count Badge -->
      <rect x="${w - 60}" y="10" width="48" height="18" rx="9" fill="#1e293b" />
      <text x="${w - 36}" y="22" font-family="ui-monospace, monospace" font-size="9" fill="#94a3b8" text-anchor="middle">
        ${fields.length} flds
      </text>
`;

    // Render Fields preview
    previewFields.forEach((field, fIdx) => {
      const fieldY = 48 + fIdx * 26;
      const fieldName = escapeXml(field.name || `field_${fIdx}`);
      const fieldType = escapeXml(field.type || "String");

      let keyBadge = "";
      if (field.primaryKey) {
        keyBadge = `<rect x="10" y="${fieldY + 2}" width="18" height="13" rx="3" fill="#065f46" />
        <text x="19" y="${fieldY + 12}" font-family="ui-monospace, monospace" font-size="8" font-weight="bold" fill="#6ee7b7" text-anchor="middle">PK</text>`;
      } else if (field.foreignKey) {
        keyBadge = `<rect x="10" y="${fieldY + 2}" width="18" height="13" rx="3" fill="#78350f" />
        <text x="19" y="${fieldY + 12}" font-family="ui-monospace, monospace" font-size="8" font-weight="bold" fill="#fcd34d" text-anchor="middle">FK</text>`;
      } else {
        const dotColor = field.required ? "#38bdf8" : "#475569";
        keyBadge = `<circle cx="16" cy="${fieldY + 9}" r="3" fill="${dotColor}" />`;
      }

      svgContent += `      <!-- Field: ${fieldName} -->
      <rect x="6" y="${fieldY}" width="${w - 12}" height="22" rx="4" fill="#0f172a" opacity="0.6" />
      ${keyBadge}
      <text x="34" y="${fieldY + 15}" font-family="ui-monospace, monospace" font-size="10" fill="#e2e8f0">
        ${fieldName}
      </text>
      <!-- Type Badge -->
      <text x="${w - 16}" y="${fieldY + 15}" font-family="ui-monospace, monospace" font-size="9" fill="#38bdf8" text-anchor="end">
        ${fieldType}
      </text>
`;
    });

    if (fields.length > 8) {
      const moreY = 48 + 8 * 26 + 14;
      svgContent += `      <text x="${w / 2}" y="${moreY}" font-family="ui-monospace, monospace" font-size="9" fill="#64748b" text-anchor="middle">
        +${fields.length - 8} more fields
      </text>\n`;
    }

    svgContent += `    </g>\n`;
  });

  svgContent += `  </g>\n</svg>`;
  return svgContent;
}

/**
 * Exports and downloads the ERD as a vector .SVG file.
 */
export function exportErdAsSvg(nodes, edges, title = "ArchMind AI Database ERD") {
  const svgXml = generateErdSvg(nodes, edges, title);
  const blob = new Blob([svgXml], { type: "image/svg+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const safeName = title.toLowerCase().replace(/[^a-z0-9_-]/g, "_");

  const a = document.createElement("a");
  a.href = url;
  a.download = `${safeName}.svg`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Exports and downloads the ERD as a high-resolution .PNG file.
 */
export function exportErdAsPng(nodes, edges, title = "ArchMind AI Database ERD") {
  const svgXml = generateErdSvg(nodes, edges, title);
  const svgBlob = new Blob([svgXml], { type: "image/svg+xml;charset=utf-8" });
  const url = URL.createObjectURL(svgBlob);
  const img = new Image();

  img.onload = () => {
    // 2x Retina scale for crisp lines
    const scale = 2;
    const canvas = document.createElement("canvas");
    canvas.width = img.width * scale;
    canvas.height = img.height * scale;
    const ctx = canvas.getContext("2d");

    ctx.scale(scale, scale);
    ctx.drawImage(img, 0, 0);

    const safeName = title.toLowerCase().replace(/[^a-z0-9_-]/g, "_");
    canvas.toBlob((blob) => {
      if (!blob) return;
      const pngUrl = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = pngUrl;
      a.download = `${safeName}.png`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(pngUrl);
      URL.revokeObjectURL(url);
    }, "image/png");
  };

  img.src = url;
}

