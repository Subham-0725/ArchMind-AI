// server/src/devops/generators/cicd.generator.js
//
// Grounded CI/CD Workflow Generator for ArchMind AI (Phase 5).
// Generates GitHub Actions workflows strictly grounded in repository tools,
// scripts, dependency caching, and least-privilege permissions.

import { validateCicdWorkflow } from "../validators/cicd.validator.js";

/**
 * Generates a deterministic GitHub Actions CI/CD workflow based on grounded context.
 *
 * @param {Object} context - Collected DevOps context
 * @param {Object} [options]
 * @returns {string} YAML workflow content
 */
export function generateDeterministicCicd(context, options = {}) {
  const lang = (context.primaryLanguage || "JavaScript").toLowerCase();
  const pkgManager = context.packageManager || "npm";
  const defaultBranch = options.defaultBranch || "main";

  // 1. Node.js / JavaScript / TypeScript
  if (lang.includes("javascript") || lang.includes("typescript") || lang.includes("node")) {
    const nodeVer = context.runtimeVersion || "20";
    const hasTest = Boolean(context.testScript);
    const hasLint = Boolean(context.lintScript);
    const hasBuild = Boolean(context.buildScript);

    let setupSteps = "";
    if (pkgManager === "pnpm") {
      setupSteps = `      - name: Setup pnpm
        uses: pnpm/action-setup@v3
        with:
          version: latest

      - name: Setup Node.js ${nodeVer}
        uses: actions/setup-node@v4
        with:
          node-version: ${nodeVer}
          cache: 'pnpm'

      - name: Install dependencies
        run: ${context.installCommand || "pnpm install --frozen-lockfile"}
`;
    } else if (pkgManager === "yarn") {
      setupSteps = `      - name: Setup Node.js ${nodeVer}
        uses: actions/setup-node@v4
        with:
          node-version: ${nodeVer}
          cache: 'yarn'

      - name: Install dependencies
        run: ${context.installCommand || "yarn install --frozen-lockfile"}
`;
    } else {
      setupSteps = `      - name: Setup Node.js ${nodeVer}
        uses: actions/setup-node@v4
        with:
          node-version: ${nodeVer}
          cache: 'npm'

      - name: Install dependencies
        run: ${context.installCommand || "npm ci"}
`;
    }

    let verificationSteps = "";
    if (hasLint) {
      verificationSteps += `      - name: Code Quality & Lint
        run: ${context.lintScript}
`;
    }
    if (hasTest) {
      verificationSteps += `      - name: Run Test Suite
        run: ${context.testScript}
`;
    }
    if (hasBuild) {
      verificationSteps += `      - name: Build Application
        run: ${context.buildScript}
`;
    }

    if (!verificationSteps) {
      verificationSteps = `      - name: Verify package integrity
        run: npm audit --audit-level=moderate || true
`;
    }

    return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
name: CI

on:
  push:
    branches: [ ${defaultBranch} ]
  pull_request:
    branches: [ ${defaultBranch} ]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  build-and-test:
    name: Build & Test
    runs-on: ubuntu-latest

    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

${setupSteps}${verificationSteps}`;
  }

  // 2. Python
  if (lang.includes("python")) {
    const pyVer = context.runtimeVersion || "3.11";
    const hasTest = Boolean(context.testScript);

    return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
name: CI

on:
  push:
    branches: [ ${defaultBranch} ]
  pull_request:
    branches: [ ${defaultBranch} ]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  build-and-test:
    name: Python CI
    runs-on: ubuntu-latest

    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Set up Python ${pyVer}
        uses: actions/setup-python@v5
        with:
          python-version: "${pyVer}"
          cache: 'pip'

      - name: Install dependencies
        run: |
          python -m pip install --upgrade pip
          ${context.installCommand || "pip install -r requirements.txt"}

${
  hasTest
    ? `      - name: Run tests
        run: ${context.testScript}
`
    : `      - name: Syntax check
        run: python -m compileall .
`
}`;
  }

  // 3. Go
  if (lang.includes("go")) {
    const goVer = context.runtimeVersion || "1.22";
    return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
name: CI

on:
  push:
    branches: [ ${defaultBranch} ]
  pull_request:
    branches: [ ${defaultBranch} ]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  build-and-test:
    name: Go CI
    runs-on: ubuntu-latest

    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Set up Go ${goVer}
        uses: actions/setup-go@v5
        with:
          go-version: "${goVer}"
          cache: true

      - name: Download modules
        run: go mod download

      - name: Run tests
        run: go test -v ./...

      - name: Build binary
        run: go build -v ./...
`;
  }

  // 4. Fallback Generic
  return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
name: CI

on:
  push:
    branches: [ ${defaultBranch} ]
  pull_request:
    branches: [ ${defaultBranch} ]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  build:
    name: Continuous Integration
    runs-on: ubuntu-latest

    steps:
      - name: Checkout code
        uses: actions/checkout@v4

      - name: Validate workspace
        run: |
          echo "Repository checked out successfully."
          ls -la
`;
}

/**
 * Generates a repository-grounded GitHub Actions workflow using Groq LLM or deterministic fallback.
 *
 * @param {Object} context - Collected repository DevOps context
 * @param {Object} [options]
 * @param {Object} [groqService] - Optional GroqChatService instance
 * @returns {Promise<{
 *   filePath: string,
 *   content: string,
 *   validation: Object,
 *   metadata: Object
 * }>}
 */
export async function generateCicdWorkflow(context, options = {}, groqService = null) {
  const hasExisting = Boolean(context.existingCicd?.length > 0);
  const existingPath = hasExisting ? context.existingCicd[0] : null;
  const filePath = ".github/workflows/ci.yml";

  let content = "";
  let provider = "deterministic";

  if (groqService && options.useAi !== false) {
    try {
      const prompt = `You are a Principal DevOps Engineer creating a GitHub Actions CI/CD workflow (.github/workflows/ci.yml) for an analyzed repository.
Strictly adhere to the following repository evidence:
- Project Name: ${context.projectName}
- Primary Language: ${context.primaryLanguage} (v${context.runtimeVersion || "LTS"})
- Package Manager: ${context.packageManager || "npm"}
- Install Command: ${context.installCommand || "npm ci"}
- Available Scripts in package.json: ${JSON.stringify(context.scripts || {})}
- Build Script: ${context.buildScript || "none"}
- Test Script: ${context.testScript || "none"}
- Lint Script: ${context.lintScript || "none"}

Rules:
1. Output ONLY the raw YAML content. Do NOT wrap in backticks, markdown, or conversational text.
2. Triggers: push and pull_request on main/master, plus workflow_dispatch.
3. Specify permissions: contents: read.
4. Use actions/checkout@v4 and actions/setup-${context.primaryLanguage === "Python" ? "python@v5" : "node@v4"} with dependency caching.
5. Do NOT invent test or lint scripts! If no test script is listed above, omit the test step or run syntax check.
6. NEVER include deployment steps requiring external credentials unless explicitly requested.
7. NEVER hardcode secrets or tokens in the YAML.`;

      const response = await groqService.chat({
        messages: [{ role: "user", content: prompt }],
        temperature: 0.1,
      });

      let rawText = response?.message?.content || "";
      if (rawText.startsWith("```")) {
        rawText = rawText.replace(/^```(?:yaml|yml)?\s*/i, "").replace(/\s*```$/i, "").trim();
      }

      if (rawText && rawText.includes("jobs:") && rawText.includes("runs-on")) {
        content = rawText;
        provider = "groq";
      }
    } catch {
      // Fallback safely to deterministic generator
    }
  }

  if (!content) {
    content = generateDeterministicCicd(context, options);
    provider = "deterministic";
  }

  // Run deterministic validation
  const validation = validateCicdWorkflow(content, { scripts: context.scripts });

  return {
    filePath,
    content,
    validation,
    metadata: {
      runtime: context.primaryLanguage,
      packageManager: context.packageManager,
      hasTests: Boolean(context.testScript),
      hasLint: Boolean(context.lintScript),
      hasBuild: Boolean(context.buildScript),
      hasExistingArtifact: hasExisting,
      existingFilePath: existingPath,
      targetPlatform: "github-actions",
      provider,
      options,
    },
  };
}

