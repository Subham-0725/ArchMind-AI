//
// Grounded Dockerfile Generator for ArchMind AI (Phase 5).
// Supports multi-stage builds, non-root user execution, layer caching,
// and package manager alignment. Provides Groq LLM generation with
// deterministic fallback and automatic deterministic validation.

import { validateDockerfile } from "../validators/dockerfile.validator.js";

/**
 * Deterministic fallback generator for Dockerfiles based on grounded context.
 *
 * @param {Object} context - Collected DevOps context
 * @param {Object} [options]
 * @returns {string} Dockerfile content
 */
export function generateDeterministicDockerfile(context, options = {}) {
  const lang = (context.primaryLanguage || "JavaScript").toLowerCase();
  const port = context.port || null;
  const pkgManager = context.packageManager || "npm";
  const startCmd = context.startScript || "npm start";
  const buildCmd = context.buildScript || null;
  const isTypeScript = context.frameworks?.includes("TypeScript") || Boolean(buildCmd);

  // 1. Node.js / JavaScript / TypeScript
  if (lang.includes("javascript") || lang.includes("typescript") || lang.includes("node")) {
    const nodeVer = context.runtimeVersion || "20";

    if (isTypeScript || buildCmd) {
      // Multi-stage build for compiled Node apps
      return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
# Multi-stage production build for Node.js / TypeScript

# ── Stage 1: Build & Dependencies ──
FROM node:${nodeVer}-alpine AS builder
WORKDIR /app

# Enable modern package managers if needed
${pkgManager === "pnpm" ? "RUN corepack enable && corepack prepare pnpm@latest --activate\n" : ""}${
        pkgManager === "yarn" ? "RUN corepack enable && corepack prepare yarn@stable --activate\n" : ""
      }
# Copy dependency manifests first for optimal layer caching
COPY package.json ${context.lockfile ? context.lockfile + " " : ""}./
RUN ${context.installCommand || "npm ci"}

# Copy source code and run build
COPY . .
${buildCmd ? `RUN ${buildCmd}\n` : ""}
# Prune development dependencies for production
${pkgManager === "npm" ? "RUN npm prune --production\n" : ""}${
        pkgManager === "pnpm" ? "RUN pnpm prune --prod\n" : ""
      }
# ── Stage 2: Minimal Production Runner ──
FROM node:${nodeVer}-alpine AS runner
WORKDIR /app

ENV NODE_ENV=production

# Run as non-root user
USER node

# Copy production artifacts
COPY --chown=node:node --from=builder /app/package.json ./
${context.lockfile ? `COPY --chown=node:node --from=builder /app/${context.lockfile} ./\n` : ""}COPY --chown=node:node --from=builder /app/node_modules ./node_modules
COPY --chown=node:node --from=builder /app/dist ./dist 2>/dev/null || COPY --chown=node:node --from=builder /app/build ./build 2>/dev/null || COPY --chown=node:node --from=builder /app/src ./src 2>/dev/null || true

${port ? `EXPOSE ${port}\n` : "# EXPOSE <port> (Configure application port)\n"}
CMD ${formatExecCmd(startCmd)}
`;
    }

    // Single-stage optimized Dockerfile for standard Node.js
    return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
FROM node:${nodeVer}-alpine
WORKDIR /app

ENV NODE_ENV=production

${pkgManager === "pnpm" ? "RUN corepack enable && corepack prepare pnpm@latest --activate\n" : ""}${
      pkgManager === "yarn" ? "RUN corepack enable && corepack prepare yarn@stable --activate\n" : ""
    }
# Copy package manifests first for layer caching
COPY package.json ${context.lockfile ? context.lockfile + " " : ""}./
RUN ${context.installCommand || "npm ci --omit=dev"}

# Copy application source
COPY . .

# Run as built-in non-root node user
USER node

${port ? `EXPOSE ${port}\n` : "# EXPOSE <port> (Configure application port)\n"}
CMD ${formatExecCmd(startCmd)}
`;
  }

  // 2. Python
  if (lang.includes("python")) {
    const pyVer = context.runtimeVersion || "3.11";
    return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
FROM python:${pyVer}-slim
WORKDIR /app

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

# Install system dependencies if required
RUN apt-get update && apt-get install -y --no-install-recommends \\
    curl \\
    && rm -rf /var/lib/apt/lists/*

# Create and switch to non-root user
RUN useradd -m -u 1000 appuser

# Copy requirements first for Docker caching
${context.lockfile ? `COPY ${context.lockfile} ./\n` : "COPY requirements.txt ./\n"}RUN pip install --no-cache-dir -r ${context.lockfile || "requirements.txt"}

# Copy application code
COPY . .
RUN chown -R appuser:appuser /app

USER appuser

${port ? `EXPOSE ${port}\n` : "# EXPOSE <port> (Configure application port)\n"}
CMD ${formatExecCmd(startCmd)}
`;
  }

  // 3. Go
  if (lang.includes("go")) {
    const goVer = context.runtimeVersion || "1.22";
    return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
# Multi-stage production build for Go binary

FROM golang:${goVer}-alpine AS builder
WORKDIR /app

COPY go.mod go.sum* ./
RUN go mod download

COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -ldflags="-w -s" -o /app/server .

FROM alpine:3.19 AS runner
WORKDIR /app

RUN adduser -D -u 1000 appuser
USER appuser

COPY --from=builder /app/server .

${port ? `EXPOSE ${port}\n` : "# EXPOSE <port>\n"}
CMD ["./server"]
`;
  }

  // 4. Generic / Unknown Fallback
  return `# Generated by ArchMind AI (Phase 5: DevOps Intelligence)
FROM alpine:3.19
WORKDIR /app

# Add application source
COPY . .

${port ? `EXPOSE ${port}\n` : "# EXPOSE <port>\n"}
CMD ["sh", "-c", "echo 'Application ready' && sleep infinity"]
`;
}

/**
 * Converts a shell string command into JSON array exec form.
 *
 * @param {string} cmd
 * @returns {string}
 */
function formatExecCmd(cmd) {
  if (!cmd) return '["npm", "start"]';
  const parts = cmd.trim().split(/\s+/);
  return JSON.stringify(parts);
}

/**
 * Generates a repository-grounded Dockerfile using Groq LLM or deterministic fallback.
 *
 * @param {Object} context - Collected repository DevOps context
 * @param {Object} [options]
 * @param {Object} [groqService] - Optional GroqChatService instance
 * @returns {Promise<{
 *   filePath: string,
 *   content: string,
 *   validation: Object,
 *   metadata: Object
 * }>}
 */
export async function generateDockerfile(context, options = {}, groqService = null) {
  const hasExisting = Boolean(context.existingDockerfiles?.length > 0);
  const existingPath = hasExisting ? context.existingDockerfiles[0] : null;
  const filePath = "Dockerfile";

  let content = "";
  let provider = "deterministic";

  if (groqService && options.useAi !== false) {
    try {
      const prompt = `You are a Principal DevOps Engineer generating a production-ready Dockerfile for an analyzed repository.
Strictly adhere to the following repository evidence:
- Project Name: ${context.projectName}
- Language / Runtime: ${context.primaryLanguage} (v${context.runtimeVersion || "LTS"})
- Package Manager: ${context.packageManager || "npm"}
- Lockfile: ${context.lockfile || "none"}
- Install Command: ${context.installCommand || "npm ci"}
- Build Script: ${context.buildScript || "none"}
- Startup Command: ${context.startScript || "npm start"}
- Port: ${context.port || "unknown"}
- Frameworks: ${context.frameworks?.join(", ") || "none"}
- Multi-Stage needed: ${Boolean(context.buildScript)}

Requirements:
1. Output ONLY the raw Dockerfile content. No markdown code blocks, no explanation, no backticks.
2. Use an official, minimal base image (e.g. alpine or slim).
3. Copy package manifests first for optimal layer caching.
4. If a build step exists, use a multi-stage build.
5. Configure a non-root user (e.g. USER node or create appuser).
6. Do NOT invent ports or commands not listed above. If port is unknown, omit or comment EXPOSE.
7. NEVER hardcode secrets, passwords, or credentials.`;

      const response = await groqService.chat({
        messages: [{ role: "user", content: prompt }],
        temperature: 0.1,
      });

      let rawText = response?.message?.content || "";
      if (rawText.startsWith("```")) {
        rawText = rawText.replace(/^```(?:dockerfile|docker)?\s*/i, "").replace(/\s*```$/i, "").trim();
      }

      if (rawText && rawText.includes("FROM")) {
        content = rawText;
        provider = "groq";
      }
    } catch (err) {
      // Groq failed or timed out — fallback safely
    }
  }

  if (!content) {
    content = generateDeterministicDockerfile(context, options);
    provider = "deterministic";
  }

  // Run deterministic validation
  const validation = validateDockerfile(content, options);

  return {
    filePath,
    content,
    validation,
    metadata: {
      runtime: context.primaryLanguage,
      runtimeVersion: context.runtimeVersion,
      packageManager: context.packageManager,
      framework: context.frameworks?.[0] || null,
      port: context.port,
      hasExistingArtifact: hasExisting,
      existingFilePath: existingPath,
      targetPlatform: "docker",
      provider,
      options,
    },
  };
}

